export function formatSpeakerDisplay(part, lang = 'en') {
  const t = I18N[lang] || I18N.en;
  const spk = (part.speaker || '').trim();
  const asst = (part.assistant || '').trim();
  if (!spk) return t.unassigned;
  if (asst && !part.isTalk) {
    return `${spk} (${t.asstShort}: ${asst})`;
  }
  return spk;
}
